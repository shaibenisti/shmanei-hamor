// Structured transcription of the printed information sheets that ship with the
// products (see docs/product-guides/). The Hebrew copy is copied verbatim —
// only the structure, keys and ids are English. Nothing is read from disk at
// runtime; this module is the single source of truth for the UI.

/** How a section is rendered. */
export type SectionTone =
  /** Regular editorial block. */
  | "default"
  /** Soft aside — background/context rather than instructions. */
  | "note"
  /** Muted caution block (אזהרות). */
  | "warning"
  /** Centered serif blessing. */
  | "verse";

export type DetailSection = {
  /** Hebrew heading exactly as it appears on the sheet. Omitted for opening blocks. */
  title?: string;
  /** Flowing lines, each rendered as its own paragraph. */
  paragraphs?: string[];
  /** Short lines rendered as a bulleted list. */
  items?: string[];
  tone?: SectionTone;
};

/**
 * Per-product colour pair. `base` carries text and hairlines and is kept dark
 * enough to stay readable on cream; `soft` is only ever used as a wash.
 */
export type Accent = { base: string; soft: string };

export type ProductDetail = {
  /** Matches the `id` of an entry in `products`. */
  id: string;
  /** Headline as written on the sheet. */
  title: string;
  subtitle?: string;
  sections: DetailSection[];
  accent: Accent;
};

